#!/usr/bin/env node
// Refinement curve: the ground-truth replay of the same recorded C1 (and C2) calls at successive
// kit commits of enclawed-oss, from data/refinement-curve.json (one replay per commit, each with
// that commit's own replay script and one fixed copy of data/call-truth.json).
// Writes generated/refinement.tex (the table) and generated/refinement-macros.tex (the numbers the
// prose cites). Counts are over the calls the current release counts (the common call set), so
// every row is measured on the same calls.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "refinement-curve.json"), "utf8"));
const steps = data.steps;
if (!steps?.length) {throw new Error("refinement-curve.json: no steps");}

const tex = (s) => String(s).replace(/\\/g, "\\textbackslash{}").replace(/([&%$#_{}])/g, "\\$1").replace(/~/g, "\\textasciitilde{}");
const n = (v) => (v === null || v === undefined ? "--" : String(v));
const rows = steps.filter((s) => s.inTable).map((s) => {
  const c2 = s.C2 ? [n(s.C2.fn), n(s.C2.fp)] : ["--", "--"];
  return `\\texttt{${s.commit.slice(0, 9)}} & ${s.date.slice(11, 16)} & ${tex(s.refinement)} & ${n(s.C1.fn)} & ${n(s.C1.fp)} & ${c2[0]} & ${c2[1]} \\\\`;
});
const table = [
  "% GENERATED by scripts/make-refinement.mjs from data/refinement-curve.json -- do not edit.",
  "\\begin{tabularx}{\\linewidth}{@{}ll>{\\raggedright\\arraybackslash}Xrrrr@{}}",
  "\\toprule",
  "Kit commit & Time & Refinement (from the commit message) & C1 FN & C1 FP & C2 FN & C2 FP \\\\",
  "\\midrule",
  ...rows,
  "\\bottomrule",
  "\\end{tabularx}",
].join("\n");
fs.writeFileSync(path.join(ROOT, "generated", "refinement.tex"), table + "\n");

const first = steps[0], last = steps[steps.length - 1];
// Steps after the baseline that change a count (the refinements the table shows).
const refinements = steps.slice(1).filter((s, i) => s.C1.fp !== steps[i].C1.fp || s.C1.fn !== steps[i].C1.fn).length;
const firstZeroFn = steps.find((s, i) => s.C1.fn === 0 && steps.slice(i).every((t) => t.C1.fn === 0));
const M = [];
const m = (k, v) => M.push(`\\newcommand{\\${k}}{${v}}`);
m("RefCalls", String(last.C1.calls));
m("RefLastCommit", `\\texttt{${last.commit.slice(0, 9)}}`);
m("RefCommits", String(steps.length));
m("RefSteps", String(refinements));
m("RefFirstFP", String(first.C1.fp));
m("RefFirstFN", String(first.C1.fn));
m("RefLastFP", String(last.C1.fp));
m("RefLastFN", String(last.C1.fn));
m("RefMaxFN", String(Math.max(...steps.map((s) => s.C1.fn))));
m("RefFnZeroFrom", `\\texttt{${(firstZeroFn ?? last).commit.slice(0, 9)}}`);
m("RefFpZeroFrom", `\\texttt{${steps.find((s, i) => steps.slice(i).every((t) => t.C1.fp === 0))?.commit.slice(0, 9) ?? "--"}}`);
m("RefUnchanged", String(steps.length - 1 - refinements));
m("RefUndetermined", String(last.C1.undetermined ?? 0));
const fpZero = steps.find((s, i) => steps.slice(i).every((t) => t.C1.fp === 0));
m("RefHoursToZero", String(Math.round((Date.parse(fpZero.date) - Date.parse(first.date)) / 36e5)));
m("RefHours", String(Math.round((Date.parse(last.date) - Date.parse(first.date)) / 36e5)));
m("RefCTwoCalls", String(last.C2?.calls ?? "--"));
m("RefCTwoLastFP", String(last.C2?.fp ?? "--"));
m("RefCTwoLastFN", String(last.C2?.fn ?? "--"));
const ex = data.example;
m("RefExFrom", `\\texttt{${ex.before.commit.slice(0, 9)}}`);
m("RefExTo", `\\texttt{${ex.after.commit.slice(0, 9)}}`);
m("RefExRemoved", String(ex.removed));
m("RefExCodeRemoved", String(ex.removedByCode));
m("RefExFN", String(ex.after.fn));
m("RefExShape", String(ex.sameShapeCalls));
m("RefExNew", String(ex.newFP));
fs.writeFileSync(
  path.join(ROOT, "generated", "refinement-macros.tex"),
  "% GENERATED by scripts/make-refinement.mjs from data/refinement-curve.json -- do not edit.\n" + M.join("\n") + "\n",
);
process.stderr.write(`make-refinement: ${steps.length} commits, C1 FP ${first.C1.fp} -> ${last.C1.fp}, FN ${first.C1.fn} -> ${last.C1.fn}\n`);
